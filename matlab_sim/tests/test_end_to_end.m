function test_end_to_end()
%TEST_END_TO_END Run the complete RF-to-tracking chain without figures.

cfg = default_config();
cfg.plot.enable = false;
results = run_end_to_end(cfg);

assert(isfield(results, 'truth') && isfield(results, 'rf') && ...
    isfield(results, 'dfe') && isfield(results, 'branches'), ...
    'End-to-end result structure is incomplete.');
assert(isfield(results.branches, 'single') && ...
    isfield(results.branches, 'egc') && ...
    isfield(results.branches, 'mvdr'), ...
    'Not all diversity branches were evaluated.');

mvdrBranch = results.branches.mvdr;
assert(mvdrBranch.acquisition.success, ...
    'Default MVDR branch did not acquire the satellite.');
assert(mvdrBranch.tracking.success && ~isempty(mvdrBranch.tracking.prompt), ...
    'Default MVDR branch did not enter closed-loop tracking.');
assert(all(isfinite(mvdrBranch.tracking.carrierFrequencyHz)), ...
    'End-to-end tracking generated nonfinite values.');

b = results.truth.jammerSteeringNominal;
singleGain = abs(results.branches.single.combining.weights' * b);
mvdrGain = abs(results.branches.mvdr.combining.weights' * b);
assert(mvdrGain < singleGain, ...
    'End-to-end MVDR weights did not reduce jammer-direction gain.');
assert(height(results.metrics.summaryTable) == 3, ...
    'Summary table must contain one row per diversity mode.');

fprintf('PASS test_end_to_end\n');
end
